CREATE TABLE IF NOT EXISTS reading_work (
    id BIGINT NOT NULL COMMENT '雪花主键',
    title VARCHAR(256) NOT NULL COMMENT '作品标题',
    author_name VARCHAR(128) NULL COMMENT '作者名',
    category_name VARCHAR(128) NULL COMMENT '分类',
    cover_url VARCHAR(1024) NULL COMMENT '封面 URL',
    description TEXT NULL COMMENT '简介',
    completion_status VARCHAR(32) NOT NULL DEFAULT 'unknown' COMMENT '完结状态：serial/completed/unknown',
    word_count BIGINT NULL COMMENT '字数',
    latest_chapter_title VARCHAR(256) NULL COMMENT '最新章节标题',
    latest_chapter_updated_at DATETIME NULL COMMENT '最新章节更新时间',
    aggregation_status VARCHAR(32) NOT NULL DEFAULT 'single_source' COMMENT '归并状态：single_source/merged/suspect',
    match_key VARCHAR(512) NOT NULL COMMENT '保守归并键',
    source_count INT NOT NULL DEFAULT 1 COMMENT '已绑定来源数',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    create_by BIGINT NULL COMMENT '创建人',
    update_by BIGINT NULL COMMENT '更新人',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除：0未删除 1已删除',
    PRIMARY KEY (id),
    KEY idx_reading_work_match (match_key, deleted),
    KEY idx_reading_work_category (category_name, completion_status, deleted),
    KEY idx_reading_work_latest (latest_chapter_updated_at, update_time, id),
    KEY idx_reading_work_title_author (title, author_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='阅读统一作品';

