-- DayDayUP Reading initialization DDL
-- Target database: daydayup_reading
-- BaseEntity convention: id, create_time, update_time, create_by, update_by, deleted.

CREATE TABLE IF NOT EXISTS reading_source_definition (
    id BIGINT NOT NULL COMMENT '雪花主键',
    name VARCHAR(128) NOT NULL COMMENT '书源名称',
    site_name VARCHAR(128) NULL COMMENT '站点/分组',
    book_source_url VARCHAR(512) NOT NULL COMMENT '书源基准 URL / 幂等键',
    book_source_type TINYINT NOT NULL DEFAULT 0 COMMENT '类型：0文字 1听书 2漫画',
    origin_type VARCHAR(32) NOT NULL DEFAULT 'legado' COMMENT '来源格式：legado/custom 等',
    origin_path VARCHAR(512) NULL COMMENT '导入来源路径',
    status TINYINT NOT NULL DEFAULT 1 COMMENT '启用状态：0禁用 1启用',
    priority INT NOT NULL DEFAULT 0 COMMENT '优先级/权重',
    tags VARCHAR(512) NULL COMMENT '标签，逗号分隔',
    compile_grade VARCHAR(32) NULL COMMENT '最近编译等级：full/degraded/rejected',
    fingerprint CHAR(64) NOT NULL COMMENT '原始规则 SHA-256 指纹',
    imported_at DATETIME NULL COMMENT '最近导入时间',
    raw_content LONGTEXT NOT NULL COMMENT '脱敏后的原始书源 JSON',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    create_by BIGINT NULL COMMENT '创建人',
    update_by BIGINT NULL COMMENT '更新人',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_reading_source_definition_url (book_source_url),
    KEY idx_reading_source_definition_status (status, deleted, priority),
    KEY idx_reading_source_definition_type (book_source_type, deleted),
    KEY idx_reading_source_definition_compile (compile_grade, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='阅读书源定义';

